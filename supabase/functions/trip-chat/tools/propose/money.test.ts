import { assertEquals } from 'jsr:@std/assert@1'
import { DISTRIBUTE_FIXTURES } from './money.fixtures.ts'
import { equalShares, formatMinor, largestRemainderDistribute, minorToDecimal, parseDecimalToMinor } from './money.ts'

Deno.test('largestRemainderDistribute: parity with the client function (fixtures generated by running it)', () => {
  for (const f of DISTRIBUTE_FIXTURES) assertEquals(largestRemainderDistribute(f.total, f.weights), f.shares, JSON.stringify(f))
})

Deno.test('3-way split of 10.00 is 3.34 / 3.33 / 3.33, deterministic and exact', () => {
  const total = parseDecimalToMinor('10.00', 'GBP')!
  assertEquals(total, 1000)
  for (let i = 0; i < 5; i++) assertEquals(equalShares(total, 3), [334, 333, 333])
  assertEquals(equalShares(total, 3).reduce((a, b) => a + b, 0), total)
})

Deno.test('parseDecimalToMinor is exact and strict', () => {
  assertEquals(parseDecimalToMinor('40', 'GBP'), 4000)
  assertEquals(parseDecimalToMinor('40.5', 'GBP'), 4050)
  assertEquals(parseDecimalToMinor('0.07', 'GBP'), 7)
  assertEquals(parseDecimalToMinor('19.99', 'GBP'), 1999)
  assertEquals(parseDecimalToMinor('1.10', 'GBP'), 110)
  assertEquals(parseDecimalToMinor('40.000', 'GBP'), 4000) // trailing zeros are harmless
  assertEquals(parseDecimalToMinor('5000', 'JPY'), 5000)
  assertEquals(parseDecimalToMinor('5000.5', 'JPY'), null)
  assertEquals(parseDecimalToMinor('1.234', 'KWD'), 1234)
  for (const bad of ['', '-5', '+5', '1,000', '£5', '1e3', ' ', '5.123', '.5', '5.', 'abc', '1234567890']) {
    assertEquals(parseDecimalToMinor(bad, 'GBP'), null, bad)
  }
})

Deno.test('formatMinor prints from integers', () => {
  assertEquals(formatMinor(4000, 'GBP'), '£40.00')
  assertEquals(formatMinor(334, 'GBP'), '£3.34')
  assertEquals(formatMinor(5, 'GBP'), '£0.05')
  assertEquals(formatMinor(123456789, 'GBP'), '£1,234,567.89')
  assertEquals(formatMinor(5000, 'JPY'), '¥5,000')
  assertEquals(formatMinor(1234, 'KWD'), 'KWD 1.234')
  assertEquals(formatMinor(-400, 'EUR'), '-€4.00')
  assertEquals(minorToDecimal(4000, 'GBP'), '40.00')
})
